PREFIX = ["", "", "", "", "скажи ", "підкажи ", "слухай ", "бот, ", "а ", "так ", "ну ", "будь ласка, "]
SUFFIX = ["", "", "?", "??", "?!", " будь ласка", " пж", "!", "..."]


def noise(s: str) -> str:
    if len(s) > 6 and rnd.random() < 0.15:
        i = rnd.randrange(1, len(s) - 1)
        s = s[:i] + s[i + 1:]
    if len(s) > 6 and rnd.random() < 0.1:
        i = rnd.randrange(1, len(s) - 2)
        s = s[:i] + s[i + 1] + s[i] + s[i + 2:]
    return s[:1].upper() + s[1:] if rnd.random() < 0.4 else s


def fill(tpl: str) -> str:
    c, o, t = rnd.choice(CITIES), rnd.choice(OBLASTS), rnd.choice(TYPES)
    s = tpl.format(t0=t[0], t1=t[1], t2=t[2], pn=c[0], pg=c[1], pl=c[2], pa=c[3], pi=c[4],
                   ol=o[0], oa=o[1], ot=o[2], n=rnd.choice([5, 10, 15, 20, 25, 30, 50]))
    return noise(rnd.choice(PREFIX) + s + rnd.choice(SUFFIX))


def main(per_intent: int = 300) -> None:
    out = ROOT / "data" / "intents" / "synth.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for intent, tpls in T.items():
        seen = set()
        for _ in range(per_intent * 4):
            s = fill(rnd.choice(tpls))
            if s.lower() not in seen:
                seen.add(s.lower())
                rows.append({"text": s, "intent": intent})
            if len(seen) >= per_intent:
                break
    rnd.shuffle(rows)
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
    print(len(rows), out)


if __name__ == "__main__":
    main()
