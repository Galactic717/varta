def ask(intent: str, batch: str, n: int = 40) -> list[str]:
    prompt = (f"Під час повітряної атаки людина пише чат-боту, який бачить карту загроз України. "
              f"Напиши {n} різних питань-повідомлень українською на тему: {DESC[intent]}.\n{STYLE[batch]}\n"
              f"Виведи лише список, по одному повідомленню на рядок, без нумерації й пояснень.")
    r = httpx.post(URL, json={"model": "gemma4", "messages": [{"role": "user", "content": prompt}],
                              "temperature": 1.0, "top_p": 0.95, "max_tokens": 2500,
                              "chat_template_kwargs": {"enable_thinking": False}}, timeout=900)
    r.raise_for_status()
    text = r.json()["choices"][0]["message"]["content"]
    lines = [re.sub(r"^\s*(\d+[.)]|[-*•])\s*", "", ln).strip().strip('"«»') for ln in text.splitlines()]
    return [ln for ln in lines if 2 <= len(ln) <= 200]


def main() -> None:
    out = ROOT / "data" / "intents" / "llm_questions.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    done = set()
    if out.exists():
        done = {(r["intent"], r["batch"]) for r in map(json.loads, out.read_text(encoding="utf-8").splitlines())}
    for batch in sys.argv[1:] or ("A", "B"):
        for intent in DESC:
            if (intent, batch) in done:
                continue
            qs = ask(intent, batch)
            with out.open("a", encoding="utf-8") as f:
                for q in dict.fromkeys(qs):
                    f.write(json.dumps({"text": q, "intent": intent, "batch": batch}, ensure_ascii=False) + "\n")
            print(batch, intent, len(qs), flush=True)
    sys.exit(0)


if __name__ == "__main__":
    main()
