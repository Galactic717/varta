def detect_types(text: str) -> frozenset[str]:
    """Типи цілей, згадані в тексті. Порожньо = «будь-які»."""
    found: set[str] = set()
    low = text.lower()
    for rx, t in _TYPE_RE:
        if rx.search(low):
            found.add(t)
            low = rx.sub(" ", low)       # «FPV-дрон» не має стати ще й «дрон»→uav
    return frozenset(found)


def mask_types(text: str) -> str:
    """Слова-типи → «<ціль>», щоб класифікатор бачив форму питання, а не жаргон."""
    for rx, _ in _TYPE_RE:
        text = rx.sub("<ціль>", text)
    return text


def plural(n: int, forms: tuple[str, str, str]) -> str:
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return forms[0]
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return forms[1]
    return forms[2]


def type_count(type_: str, n: int) -> str:
    return f"{n} {plural(n, TYPE_FORMS.get(type_, TYPE_FORMS['unknown']))}"
